def md(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---" for _ in header) + "|\n"
    return s + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def pct(x, nd=2):
    return "–" if x is None else f"{100 * x:.{nd}f}"


def ci(c):
    return "–" if c is None else f"[{c[0]:.2f}, {c[1]:.2f}]"


TEX_MAP = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "±": r"$\pm$", "×": r"$\times$", "–": "--", "—": "---",
           "−": "$-$", "≥": r"$\geq$", "≤": r"$\leq$", "²": r"$^2$", "³": r"$^3$", "µ": r"$\mu$", "σ": r"$\sigma$",
           "ρ": r"$\rho$", "η": r"$\eta$", "κ": r"$\kappa$", "γ": r"$\gamma$", "Δ": r"$\Delta$", "ξ": r"$\xi$",
           "θ": r"$\theta$", "Ω": r"$\Omega$", "̂": "", "’": "'", "→": r"$\rightarrow$", "ω": r"$\omega$", "₁": r"$_1$",
           "ν": r"$\nu$", "α": r"$\alpha$", "β": r"$\beta$", "°": r"$^\circ$", "≈": r"$\approx$", "·": r"$\cdot$", "§": r"\S{}", "√": r"$\surd$"}


def tex_escape(x: str) -> str:
    out = "".join(TEX_MAP.get(ch, ch) for ch in str(x))
    return out.replace("**", "").replace("`", "")


def md_to_tex(body: str) -> str:
    """Markdown body (tables, bold headings, paragraphs) -> LaTeX (booktabs tabulars, small font)."""
    out, block = [], []

    def flush():
        if not block:
            return
        cells = [[c.strip() for c in ln.strip().strip("|").split("|")] for ln in block if not set(ln.replace("|", "").strip()) <= {"-"}]
        n = len(cells[0])
        out.append(r"\begin{tabular}{" + "l" * n + "}\n\\toprule")
        out.append(" & ".join(tex_escape(c) for c in cells[0]) + r" \\ \midrule")
        out.extend(" & ".join(tex_escape(c) for c in r) + r" \\" for r in cells[1:])
        out.append("\\bottomrule\n\\end{tabular}\n")
        block.clear()

    for ln in body.splitlines():
        if ln.strip().startswith("|"):
            block.append(ln)
            continue
        flush()
        if ln.strip():
            t = ln.strip()
            out.append((r"\par\textbf{" + tex_escape(t[2:-2]) + "}\\par" if t.startswith("**") and t.endswith("**") else tex_escape(t) + r"\par"))
    flush()
    return "\n".join(out)


def write(name, title, body, sources, notes=()):
    OUT.mkdir(parents=True, exist_ok=True)
    txt = f"# {title}\n\n{body}\n" + "".join(f"\n{n}\n" for n in notes) + "\nSource: " + ", ".join(f"`{s}`" for s in sources) + "\n"
    (OUT / f"{name}.md").write_text(txt)
    cap = title.split(". ", 1)[1] if title.startswith("Table") and ". " in title else title
    tex = ("% generated by experiments/make_tables.py from " + ", ".join(sources) + "; do not edit\n"
           r"\begin{table}[tbp]\centering\scriptsize" + "\n" + r"\caption{" + tex_escape(cap) + "}\\label{tab:" + name + "}\n"
           r"\resizebox{\textwidth}{!}{\begin{minipage}{1.6\textwidth}\centering" + "\n" + md_to_tex(body) + "\n"
           + "".join(r"\par\smallskip{\footnotesize " + tex_escape(n) + "}\n" for n in notes)
           + r"\end{minipage}}" + "\n" + r"\end{table}" + "\n")
    (OUT / f"{name}.tex").write_text(tex)
    print("wrote", name)


def missing(name, title, src):
    write(name, title, f"**Not yet available:** `{src}` has not been written.", [src])


