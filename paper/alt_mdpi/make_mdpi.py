"""Alternative build of the paper in the MDPI LaTeX template (Sensors), from the same sources as paper/main.tex.

Fallback target only: the MSSP version (paper/main.tex) stays the primary one. Nothing in paper/ is changed;
the sections, abstract, number macros, tables, figures and bibliography are copied as they are and wrapped in
the MDPI front and back matter.

The MDPI class is not on CTAN and not in this repository: download the LaTeX template from
https://www.mdpi.com/authors/latex, unpack it, and pass its folder (the one that contains Definitions/mdpi.cls):

    python3 paper/alt_mdpi/make_mdpi.py --template /path/to/MDPI_template      # build folder + PDF
    python3 paper/alt_mdpi/make_mdpi.py --template /path/to/MDPI_template --no-pdf

Output: paper/alt_mdpi/build/ (main_mdpi.tex, Definitions/, sections, generated/numbers.tex, tables/, figures/,
refs.bib), main_mdpi.pdf when latexmk is available, and paper/alt_mdpi/wheelset_mdpi_overleaf.zip, which is
the build folder ready to upload to Overleaf. Run `make -C paper` (or `make reproduce`) first so that the
number macros and tables are current. Checks the MDPI limits it can (abstract 200 words) and prints them.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
ROOT = PAPER.parent
SECTIONS = ["sec1_intro", "sec2_model", "sec3_method", "sec4_results", "sec5_discussion", "sec6_conclusions"]
ABSTRACT_MAX_WORDS = 200          # MDPI Instructions for Authors (Sensors): about 200 words, single paragraph

TITLE = (r"Tracking the Support Stiffness of Railway Wheelset Bearings from Multi-Speed Axle-Box Acceleration "
         r"without Measuring Rail Roughness: A Multi-Pass Debiased Whittle Likelihood")
KEYWORDS = ("axle-box acceleration; wheelset bearing support stiffness; condition monitoring; debiased Whittle "
            "likelihood; rail roughness; vehicle--track interaction; system identification")

# backmatter.tex section titles -> MDPI back-matter commands
BACK = {"CRediT authorship contribution statement": "authorcontributions",
        "Funding": "funding",
        "Data availability": "dataavailability",
        "Acknowledgements": "acknowledgments",
        "Declaration of competing interest": "conflictsofinterest"}
AI_TITLE = "Declaration of generative AI and AI-assisted technologies in the manuscript preparation process"


def block(text: str, begin: str, end: str) -> str:
    i, j = text.index(begin) + len(begin), text.index(end)
    return text[i:j].strip()


def strip_comments(s: str) -> str:
    return "\n".join(re.sub(r"(?<!\\)%.*$", "", line) for line in s.splitlines())


def words(tex: str) -> int:
    t = re.sub(r"\\[A-Za-z]+\*?(\{[^}]*\})?", " x ", strip_comments(tex))      # a macro (a number) counts as one word
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9.\-]*", t))


def backmatter() -> str:
    t = strip_comments((PAPER / "backmatter.tex").read_text())
    parts = re.split(r"\\section\*\{([^}]*)\}", t)
    sec = {parts[i].strip(): parts[i + 1].strip() for i in range(1, len(parts), 2)}
    out = []
    for title, cmd in BACK.items():
        body = sec.get(title, "")
        if cmd == "acknowledgments" and AI_TITLE in sec:      # MDPI: AI use is disclosed in the acknowledgments
            body = (body + "\n\n" + sec[AI_TITLE]).strip()
        out.append(f"\\{cmd}{{{body}}}")
    return "\n\n".join(out)


def main_tex(abstract: str) -> str:
    return rf"""% MDPI (Sensors) build of paper/main.tex, generated by paper/alt_mdpi/make_mdpi.py; do not edit by hand.
\documentclass[sensors,article,submit,pdftex,moreauthors]{{Definitions/mdpi}}
\makeatletter
\@ifpackageloaded{{natbib}}{{}}{{\usepackage[numbers,square,compress]{{natbib}}}}
\makeatother
\usepackage{{bm,longtable}}
\graphicspath{{{{figures/}}}}
\def\tabdir{{tables}}
\newcommand{{\inputtable}}[1]{{\input{{\tabdir/#1}}}}
\input{{doi}}
\input{{generated/numbers.tex}}

\firstpage{{1}}
\makeatletter
\setcounter{{page}}{{\@firstpage}}
\makeatother
\pubvolume{{1}}
\issuenum{{1}}
\articlenumber{{0}}
\pubyear{{2026}}
\copyrightyear{{2026}}
\datereceived{{ }}
\daterevised{{ }}
\dateaccepted{{ }}
\datepublished{{ }}
\hreflink{{https://doi.org/}}

\Title{{{TITLE}}}
\TitleCitation{{Tracking the Support Stiffness of Railway Wheelset Bearings}}
% Author slots: to be filled by the authors (as in paper/authors.tex)
\Author{{[Given name 1] [Family name 1] $^{{1,}}$*\orcidA{{}} and [Given name 2] [Family name 2] $^{{2}}$}}
\AuthorNames{{[Given name 1] [Family name 1] and [Given name 2] [Family name 2]}}
\AuthorCitation{{[Family name 1], [Initial 1].; [Family name 2], [Initial 2].}}
\address{{%
$^{{1}}$ \quad [Department, Institution, City, Postcode, Country]; [e-mail]\\
$^{{2}}$ \quad [Department, Institution, City, Postcode, Country]}}
\corres{{Correspondence: [corresponding.author@institution]}}

\abstract{{{abstract}}}

\keyword{{{KEYWORDS}}}

\begin{{document}}

{chr(10).join(f"\\input{{{s}}}" for s in SECTIONS)}

\vspace{{6pt}}

{backmatter()}

\begin{{adjustwidth}}{{-\extralength}}{{0cm}}
\reftitle{{References}}
\bibliography{{refs}}
\end{{adjustwidth}}
\end{{document}}
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", required=True, help="unpacked MDPI LaTeX template (folder with Definitions/mdpi.cls)")
    ap.add_argument("--no-pdf", action="store_true", help="only write the build folder and the Overleaf zip")
    a = ap.parse_args()
    tdef = Path(a.template).expanduser().resolve() / "Definitions"
    if not (tdef / "mdpi.cls").exists():
        print(f"make_mdpi: {tdef / 'mdpi.cls'} not found; download the template from "
              "https://www.mdpi.com/authors/latex and pass its folder with --template", file=sys.stderr)
        return 2
    for need in ("generated/numbers.tex", "refs.bib", "doi.tex"):
        if not (PAPER / need).exists():
            print(f"make_mdpi: paper/{need} missing; run `make -C paper` first", file=sys.stderr)
            return 2
    B = HERE / "build"
    if B.exists():
        shutil.rmtree(B)
    (B / "generated").mkdir(parents=True)
    shutil.copytree(tdef, B / "Definitions")
    for s in SECTIONS:
        shutil.copy(PAPER / f"{s}.tex", B / f"{s}.tex")
    for f in ("refs.bib", "doi.tex"):
        shutil.copy(PAPER / f, B / f)
    shutil.copy(PAPER / "generated/numbers.tex", B / "generated/numbers.tex")
    shutil.copytree(ROOT / "results/tables", B / "tables", ignore=shutil.ignore_patterns("*.md", "*.json", "*.csv"))
    shutil.copytree(ROOT / "figures", B / "figures", ignore=shutil.ignore_patterns("*.json", "*.png"))
    if (B / "Definitions" / "mdpi.bst").exists():
        bst = "\\bibliographystyle{Definitions/mdpi}\n"
    else:
        bst = "\\bibliographystyle{unsrtnat}\n"
        print("make_mdpi: Definitions/mdpi.bst not in the template; using unsrtnat")
    abstract = block((PAPER / "abstract.tex").read_text(), r"\begin{abstract}", r"\end{abstract}")
    abstract = " ".join(strip_comments(abstract).split())
    tex = main_tex(abstract).replace("\\reftitle{References}\n", "\\reftitle{References}\n" + bst)
    (B / "main_mdpi.tex").write_text(tex)
    n = words(abstract)
    print(f"make_mdpi: abstract {n} words (MDPI limit about {ABSTRACT_MAX_WORDS})"
          + ("; SHORTEN before an MDPI submission" if n > ABSTRACT_MAX_WORDS else ""))
    print("make_mdpi: MDPI has no highlights and no graphical-abstract requirement; author slots are placeholders")
    status = 0
    if not a.no_pdf:
        if shutil.which("latexmk"):
            r = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "main_mdpi.tex"], cwd=B,
                               capture_output=True, text=True)
            status = r.returncode
            print("make_mdpi: PDF " + ("built: paper/alt_mdpi/build/main_mdpi.pdf" if status == 0
                                       else "FAILED; see paper/alt_mdpi/build/main_mdpi.log"))
        else:
            print("make_mdpi: latexmk not found; build folder only")
    z = HERE / "wheelset_mdpi_overleaf.zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(B.rglob("*")):
            if f.is_file() and f.suffix not in (".aux", ".log", ".fls", ".fdb_latexmk", ".out", ".blg", ".bbl", ".pdf"):
                zf.write(f, f.relative_to(B))
    print(f"make_mdpi: Overleaf zip {z.relative_to(ROOT)} (upload, set main document main_mdpi.tex, compiler pdfLaTeX)")
    return status


if __name__ == "__main__":
    sys.exit(main())
